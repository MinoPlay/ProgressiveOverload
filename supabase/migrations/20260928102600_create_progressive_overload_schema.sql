create trigger workouts_set_updated_at
before update on progressive_overload.workouts
for each row execute function progressive_overload.set_updated_at();

create trigger session_templates_set_updated_at
before update on progressive_overload.session_templates
for each row execute function progressive_overload.set_updated_at();

