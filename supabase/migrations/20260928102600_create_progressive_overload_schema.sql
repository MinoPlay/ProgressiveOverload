create function progressive_overload.initialize_default_exercises(target_user_id uuid)
returns void
language sql
security definer
set search_path = ''
as $$
    insert into progressive_overload.exercises (
        user_id,
        id,
        name,
        equipment_type,
        muscle,
        requires_weight
    )
    values
        (target_user_id, 'default-bench-press', 'Bench Press', 'barbell', 'chest', true),
        (target_user_id, 'default-squat', 'Squat', 'barbell', 'legs', true),
        (target_user_id, 'default-deadlift', 'Deadlift', 'barbell', 'legs', true),
        (target_user_id, 'default-pull-ups', 'Pull-ups', 'bodyweight', 'back', false),
        (target_user_id, 'default-overhead-press', 'Overhead Press', 'barbell', 'shoulders', true),
        (target_user_id, 'default-barbell-rows', 'Barbell Rows', 'barbell', 'back', true),
        (target_user_id, 'default-dips', 'Dips', 'bodyweight', 'triceps', false),
        (target_user_id, 'default-bicep-curls', 'Bicep Curls', 'dumbbell', 'biceps', true)
    on conflict do nothing;
$$;

revoke all on function progressive_overload.initialize_default_exercises(uuid)
from public, anon, authenticated;
grant execute on function progressive_overload.initialize_default_exercises(uuid)
to service_role;

create function progressive_overload.initialize_user_data()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    current_user_id uuid := auth.uid();
    initialized_user boolean;
begin
    if current_user_id is null then
        raise exception 'Authentication required';
    end if;
    insert into progressive_overload.user_settings (user_id)
    values (current_user_id)
    on conflict (user_id) do nothing
    returning true into initialized_user;
    if initialized_user then
        perform progressive_overload.initialize_default_exercises(current_user_id);
    end if;
end;
$$;

revoke all on function progressive_overload.initialize_user_data()
from public, anon;
grant execute on function progressive_overload.initialize_user_data()
to authenticated, service_role;
